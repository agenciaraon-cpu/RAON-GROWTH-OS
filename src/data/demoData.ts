const STAGES: Lead['stage'][] = ['novo_lead', 'contato', 'qualificado', 'orcamento', 'negociacao', 'ganho', 'perdido'];
const RESPONSIBLES = ['Roberto Lima (SDR)', 'Paula Mendes (Closer)', 'Carlos Andrade (Consultor)'];

export function generateDemoLeads(): Lead[] {
  const leads: Lead[] = [];
  const baseDate = new Date();

  for (let i = 1; i <= 100; i++) {
    const fn = FIRST_NAMES[i % FIRST_NAMES.length];
    const ln = LAST_NAMES[(i * 3) % LAST_NAMES.length];
    const origin = ORIGINS[i % ORIGINS.length];
    
    // Distribution favoring realistic pipeline:
    // 25 novos, 22 contatos, 18 qualificados, 12 orçamentos, 8 negociacao, 10 ganhos, 5 perdidos
    let stage: Lead['stage'] = 'novo_lead';
    if (i <= 25) stage = 'novo_lead';
    else if (i <= 47) stage = 'contato';
    else if (i <= 65) stage = 'qualificado';
    else if (i <= 77) stage = 'orcamento';
    else if (i <= 85) stage = 'negociacao';
    else if (i <= 95) stage = 'ganho';
    else stage = 'perdido';

    const daysAgo = Math.floor(Math.random() * 28);
    const date = new Date(baseDate.getTime() - daysAgo * 24 * 60 * 60 * 1000);
    const val = [15000, 25000, 38000, 52000, 75000, 120000, 4500, 8900][i % 8];

    leads.push({
      id: `lead-${i}`,
      organizationId: 'org-raon',
      clientId: i % 2 === 0 ? 'client-1' : (i % 3 === 0 ? 'client-2' : 'client-3'),
      name: `${fn} ${ln}`,
      phone: `(11) 9${Math.floor(1000 + Math.random() * 9000)}-${Math.floor(1000 + Math.random() * 9000)}`,
      whatsapp: `119${Math.floor(1000 + Math.random() * 9000)}${Math.floor(1000 + Math.random() * 9000)}`,
      email: `${fn.toLowerCase()}.${ln.toLowerCase()}@exemplo.com.br`,
      company: i % 3 === 0 ? `${ln} Participações & Investimentos` : `${fn} Engenharia`,
      city: i % 2 === 0 ? 'São Paulo' : 'Curitiba',
      state: i % 2 === 0 ? 'SP' : 'PR',
      origin,
      campaignName: origin === 'Meta Ads' ? 'Campanha Alto Padrão Q4' : (origin === 'Google Ads' ? 'Fundo de Funil - Imóveis Luxo' : 'Tráfego Direto WhatsApp'),
      service: i % 2 === 0 ? 'Apartamento Penthouse Jardins' : 'Tratamento Laser & Harmonização',
      responsible: RESPONSIBLES[i % RESPONSIBLES.length],
      stage,
      potentialValue: val,
      notes: i % 4 === 0 ? 'Interesse confirmado. Solicitou apresentação detalhada de fluxo financeiro.' : undefined,
      nextAction: stage === 'negociacao' ? 'Apresentação de proposta final presencial' : (stage === 'contato' ? 'Segundo follow-up por WhatsApp' : 'Qualificação BANT'),
      lastInteractionAt: new Date(date.getTime() + 10000000).toISOString(),
      createdAt: date.toISOString(),
      updatedAt: new Date().toISOString(),
    });
  }
  return leads;
}

export function generateDemoDeals(leads: Lead[]): Deal[] {
  // Generate ~30 deals from leads in later stages
  const deals: Deal[] = [];
  const dealLeads = leads.filter(l => ['qualificado', 'orcamento', 'negociacao', 'ganho', 'perdido'].includes(l.stage)).slice(0, 32);

  dealLeads.forEach((l, idx) => {
    let status: Deal['status'] = 'open';
    if (l.stage === 'ganho') status = 'won';
    else if (l.stage === 'perdido') status = 'lost';

    deals.push({
      id: `deal-${idx + 1}`,
      organizationId: l.organizationId,
      clientId: l.clientId,
      leadId: l.id,
      leadName: l.name,
      title: `Contrato: ${l.name} - ${l.service || 'Serviço Premium'}`,
      value: l.potentialValue,
      stage: l.stage,
      responsible: l.responsible,
      status,
      wonAt: status === 'won' ? l.createdAt : undefined,
      lostAt: status === 'lost' ? l.createdAt : undefined,
      lostReason: status === 'lost' ? 'Optou por concorrente com prazo menor' : undefined,
      createdAt: l.createdAt,
      updatedAt: l.updatedAt,
    });
  });

  return deals;
}

